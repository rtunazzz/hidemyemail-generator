def _run_address_command(
    coro, result_json: Optional[str], db_file: Optional[str] = None
) -> None:
    try:
        result = asyncio.run(coro)
    except KeyboardInterrupt:
        coro.close()
        return

    if result["ok"] and db_file:
        _write_through(db_file, result)
    write_result_json(result_json, result)
    if not result["ok"]:
        raise click.ClickException(result["error"]["message"])


def _write_through(db_file: str, result: dict) -> None:
    """Mirrors an accepted iCloud edit into the local database.

    Without this the address list keeps serving the pre-edit label, note, and
    forwarding state until the next full sync.
    """
    conn = connect_db(db_file)
    try:
        set_address_metadata(
            conn,
            result["email"],
            label=result.get("label"),
            note=result.get("note"),
            is_active=result.get("is_active"),
        )
    finally:
        conn.close()


