async def _generate(
    label: str,
    count: int,
    cookie_file: str,
    output_file: str,
    no_output_file: bool = False,
    region: str = DEFAULT_REGION,
    db_file: str = DEFAULT_DB_FILE,
    no_db: bool = False,
    batch_id: Optional[str] = None,
) -> dict:
    async with RichHideMyEmail(
        cookie_file=cookie_file,
        output_file=output_file,
        no_output_file=no_output_file,
        region=region,
    ) as hme:
        emails = await hme.generate(label, count)

    if emails and not no_db:
        conn = connect_db(db_file)
        try:
            for email in emails:
                # No note: a canned one would overwrite whatever the user wrote.
                upsert_address(
                    conn,
                    email,
                    label=label,
                    state="unused",
                    source="generated",
                    batch_id=batch_id,
                )
        finally:
            conn.close()

    return {
        "ok": len(emails) == count,
        "emails": emails,
        "error": None
        if len(emails) == count
        else hme.last_error
        or {"code": None, "message": "Generation failed", "retry_after": None},
    }


