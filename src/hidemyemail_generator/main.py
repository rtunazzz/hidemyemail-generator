def maildomain_suffix(region: str) -> str:
    return "com.cn" if region == "china" else "com"


def bridge_error(response: dict | None) -> dict:
    if not response:
        return {"code": None, "message": "Empty response from iCloud", "retry_after": None}

    error = response.get("error")
    if isinstance(error, dict):
        code = error.get("errorCode")
        if code is None:
            code = error.get("code")
        message = (
            error.get("errorMessage")
            or error.get("message")
            or response.get("reason")
            or "Unknown error"
        )
        retry_after = error.get("retryAfter")
    else:
        code = error if isinstance(error, int) else None
        message = response.get("reason") or str(error or "Unknown error")
        retry_after = response.get("retryAfter")

    return {
        "code": str(code) if code is not None else None,
        "message": str(message),
        "retry_after": retry_after if isinstance(retry_after, (int, float)) else None,
    }


def write_result_json(result_file: str | None, payload: dict) -> None:
    if result_file:
        path = Path(result_file)
        path.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
        path.chmod(0o600)


def account_summary(account: dict) -> dict:
    ds_info = account.get("dsInfo", {})
    full_name = ds_info.get("fullName") or " ".join(
        part for part in [ds_info.get("firstName"), ds_info.get("lastName")] if part
    )
    maildomain = account.get("webservices", {}).get("maildomainws", {})
    maildomain_host = (
        account.get("detectedMaildomainHost") or maildomain.get("url") or ""
    )
    maildomain_host = re.sub(r"^https?://", "", maildomain_host).split("/", 1)[0]
    user_partition = account.get("userPartition")
    try:
        user_partition = int(user_partition) if user_partition is not None else None
    except (TypeError, ValueError):
        user_partition = None

    return {
        "apple_id": ds_info.get("appleId") or "Unknown",
        "name": full_name or "Unknown",
        "dsid": str(ds_info.get("dsid")) if ds_info.get("dsid") is not None else None,
        "user_partition": user_partition,
        "maildomain_host": maildomain_host,
        "hide_my_email_available": bool(
            ds_info.get("isHideMyEmailFeatureAvailable")
        ),
    }


def load_cookie_context(cookie_file: str, region: str) -> tuple[str, str]:
    with open(cookie_file, "r") as f:
        content = "\n".join(
            line.strip() for line in f if not line.lstrip().startswith("//")
        ).strip()
    normalized_content = (
        content.replace('^"', '"')
        .replace("^'", "'")
        .replace("^\n", "")
        .replace("^\r\n", "")
    )

    maildomain_host = ""
    explicit_maildomain_host = re.search(
        r"(?m)^HIDEMYEMAIL_MAILDOMAIN_HOST=([A-Za-z0-9.-]+)\s*$",
        normalized_content,
    )
    if explicit_maildomain_host:
        maildomain_host = explicit_maildomain_host.group(1).strip()

    encoded_cookie = re.search(
        r"(?m)^HIDEMYEMAIL_COOKIE_BASE64=([A-Za-z0-9+/=]+)\s*$",
        normalized_content,
    )
    if encoded_cookie:
        cookie = base64.b64decode(encoded_cookie.group(1)).decode("utf-8")
        return cookie.strip(), maildomain_host

    shard = re.search(
        r"https://(p\d+)-[^/\s'\"]+\.icloud\.com(?:\.cn)?", normalized_content
    )
    if shard:
        maildomain_host = (
            f"{shard.group(1)}-maildomainws.icloud.{maildomain_suffix(region)}"
        )

    cmd_cookie_arg = re.search(
        r"(?:^|\s)(?:-b|--cookie)\s+\^\"(.+?)\^\"\s+\^?\s*-[A-Za-z]",
        content,
        re.IGNORECASE | re.DOTALL,
    )
    if cmd_cookie_arg:
        cookie = (
            cmd_cookie_arg.group(1)
            .replace('^\\^"', '"')
            .replace('\\"', '"')
            .replace('^"', '"')
            .replace("\r", "")
            .replace("\n", "")
        )
        return cookie.strip(), maildomain_host

    cookie_arg = re.search(
        r"(?:^|\s)(?:-b|--cookie)\s+\"([^\"]+)\"",
        normalized_content,
        re.IGNORECASE,
    )
    if cookie_arg:
        return cookie_arg.group(1).strip(), maildomain_host

    cookie_header = re.search(
        r"cookie\s*:\s*([^'\"\r\n]+)", normalized_content, re.IGNORECASE
    )
    if cookie_header:
        return cookie_header.group(1).strip(), maildomain_host

    lines = normalized_content.splitlines()
    return (lines[0].strip() if lines else ""), maildomain_host


async def fetch_account_info(cookie_file: str, region: str) -> dict:
    cookie, maildomain_host = load_cookie_context(cookie_file, region)
    if not cookie:
        return {"error": "Cookie file is empty"}

    return await fetch_account_info_from_cookie(cookie, region, maildomain_host)


async def fetch_account_info_from_cookie(
    cookie: str, region: str, maildomain_host: str = ""
) -> dict:
    headers = HideMyEmail.browser_headers(region, cookie)
    connector = aiohttp.TCPConnector(
        ssl_context=ssl.create_default_context(cafile=certifi.where())
    )

    async with aiohttp.ClientSession(
        headers=headers,
        timeout=aiohttp.ClientTimeout(total=30),
        connector=connector,
    ) as session:
        async with session.get(SETUP_VALIDATE_URLS[region]) as response:
            try:
                data = await response.json(content_type=None)
            except Exception:
                return {"error": f"Unexpected response from iCloud ({response.status})"}

    if response.status != 200:
        reason = data.get("reason") or data.get("error") or response.status
        return {"error": f"Failed to validate cookie: {reason}"}

    user_partition = data.get("userPartition")
    if not maildomain_host and user_partition:
        maildomain_host = (
            f"p{user_partition}-maildomainws.icloud.{maildomain_suffix(region)}"
        )

    data["detectedMaildomainHost"] = maildomain_host
    return data


def write_captured_cookie(
    cookie_file: str, cookie: str, region: str, request_url: str, maildomain_host: str
) -> None:
    path = Path(cookie_file)
    if path.exists() and path.stat().st_size > 0:
        shutil.copy2(path, path.with_name(f"{path.name}.bak"))

    encoded_cookie = base64.b64encode(cookie.encode("utf-8")).decode("ascii")
    path.write_text(
        "\n".join(
            [
                "# Generated by hidemyemail capture-cookie.",
                f"HIDEMYEMAIL_REGION={region}",
                f"HIDEMYEMAIL_REQUEST_URL={request_url}",
                f"HIDEMYEMAIL_MAILDOMAIN_HOST={maildomain_host}",
                f"HIDEMYEMAIL_COOKIE_BASE64={encoded_cookie}",
                "",
            ]
        ),
        encoding="utf-8",
    )


class RichHideMyEmail(HideMyEmail):
    def __init__(
        self,
        cookie_file: str,
        output_file: str = "",
        no_output_file: bool = False,
        region: str = DEFAULT_REGION,
    ):
        cookies = ""
        maildomain_host = ""
        if os.path.exists(cookie_file):
            cookies, maildomain_host = load_cookie_context(cookie_file, region)

        super().__init__(cookies=cookies, region=region, maildomain_host=maildomain_host)
        self.console = Console()
        self.table = Table()
        self._output_file = output_file
        self._no_output_file = no_output_file
        self.last_error = None

        if not os.path.exists(cookie_file):
            self.console.log(
                f'[bold yellow][WARN][/] No "{cookie_file}" file found! 未找到 Cookie 文件，可能无法授权访问。'
            )
        elif "X-APPLE-WEBAUTH-USER" not in self.cookies:
            self.console.log(
                "[bold yellow][WARN][/] Cookie is missing X-APPLE-WEBAUTH-USER. Cookie 缺少授权字段；请复制已登录的 iCloud 请求，优先 maildomainws 或 hme，不要用 feedbackws/reportStats。"
            )

    def _check_response(
        self, response: dict, action: str, email: Optional[str] = None
    ) -> bool:
        if not response:
            self.last_error = bridge_error(response)
            return False
        if "success" not in response or not response["success"]:
            self.last_error = bridge_error(response)
            email_prefix = f' "{email}"' if email else ""
            self.console.log(
                f"[bold red][ERR][/]{email_prefix} - Failed to {action}. 失败原因: {self.last_error['message']}"
            )
            return False
        return True

    async def _generate_one(self, label: str) -> Union[str, None]:
        # First, generate an email
        gen_res = await self.generate_email()

        if not self._check_response(gen_res, "generate email"):
            return

        email = gen_res["result"]["hme"]
        self.console.log(f'[50%] "{email}" - Successfully generated / 生成成功')

        # Then, reserve it
        reserve_res = await self.reserve_email(email, label, DEFAULT_HME_NOTE)

        if not self._check_response(reserve_res, "reserve email", email):
            return

        self.console.log(f'[100%] "{email}" - Successfully reserved / 保留成功')
        return email

    async def _generate(self, label: str, num: int):
        tasks = []
        for _ in range(num):
            task = asyncio.ensure_future(self._generate_one(label))
            tasks.append(task)

        return filter(lambda e: e is not None, await asyncio.gather(*tasks))

    async def generate(self, label: str, count: int) -> List[str]:
        try:
            self.last_error = None
            emails = []
            self.console.rule()
            if count < 1:
                self.last_error = {
                    "code": None,
                    "message": "Count should be >= 1",
                    "retry_after": None,
                }
                self.console.log("Count should be >= 1 / 数量必须大于等于 1")
                return emails
            self.console.log(f"Generating {count} email(s)... / 正在生成 {count} 个邮箱...")
            self.console.rule()

            with self.console.status("[bold green]Generating iCloud email(s)..."):
                while count > 0:
                    batch = await self._generate(
                        label,
                        count if count < MAX_CONCURRENT_TASKS else MAX_CONCURRENT_TASKS,
                    )
                    count -= MAX_CONCURRENT_TASKS
                    emails += batch

            if len(emails) > 0:
                if not self._no_output_file:
                    with open(self._output_file, "a+") as f:
                        f.write(os.linesep.join(emails) + os.linesep)

                    self.console.rule()
                    self.console.log(
                        f':star: Emails have been saved into "{self._output_file}" / 邮箱已保存'
                    )
                else:
                    self.console.rule()

                self.console.log(
                    f"[bold green]All done![/] Successfully generated [bold green]{len(emails)}[/] email(s) / 已生成 [bold green]{len(emails)}[/] 个邮箱"
                )

            return emails
        except KeyboardInterrupt:
            return []

    async def list(self, label_query: Optional[str], active: bool) -> dict:
        gen_res = await self.list_email()
        if not self._check_response(gen_res, "list emails"):
            return {"ok": False, "addresses": [], "error": self.last_error}

        self.table.add_column("Label / 标签")
        self.table.add_column("Hide My Email / 隐藏邮箱")
        self.table.add_column("Created At / 创建时间")
        self.table.add_column("Is Active / 使用中")

        addresses = []
        for row in gen_res["result"]["hmeEmails"]:
            if row["isActive"] == active and (
                label_query is None or re.search(label_query, row["label"])
            ):
                created_at = datetime.datetime.fromtimestamp(
                    row["createTimestamp"] / 1000, tz=datetime.timezone.utc
                ).isoformat()
                addresses.append(
                    {
                        "email": row["hme"],
                        "label": row["label"],
                        "created_at": created_at,
                        "is_active": bool(row["isActive"]),
                        "anonymous_id": row.get("anonymousId") or "",
                    }
                )
                self.table.add_row(
                    row["label"],
                    row["hme"],
                    str(datetime.datetime.fromtimestamp(row["createTimestamp"] / 1000)),
                    str(row["isActive"]),
                )

        self.console.print(self.table)
        return {"ok": True, "addresses": addresses, "error": None}

    async def _resolve(self, email: str) -> Optional[dict]:
        """Looks up the iCloud record for an address, needed for its anonymousId."""
        gen_res = await self.list_email()
        if not self._check_response(gen_res, "list emails"):
            return None

        for row in gen_res["result"]["hmeEmails"]:
            if row.get("hme") != email:
                continue
            if not row.get("anonymousId"):
                self.last_error = {
                    "code": None,
                    "message": f'iCloud returned no identifier for "{email}"',
                    "retry_after": None,
                }
                self.console.log(f"[bold red][ERR][/] {self.last_error['message']}")
                return None
            return row

        self.last_error = {
            "code": None,
            "message": f'No Hide My Email address matching "{email}"',
            "retry_after": None,
        }
        self.console.log(
            f'[bold red][ERR][/] {self.last_error["message"]} / 未找到匹配的隐藏邮箱'
        )
        return None

    async def set_active(self, email: str, active: bool) -> dict:
        self.last_error = None
        row = await self._resolve(email)
        if row is None:
            return {"ok": False, "email": email, "is_active": None, "error": self.last_error}

        action = "reactivate" if active else "deactivate"
        call = self.reactivate_email if active else self.deactivate_email
        res = await call(row["anonymousId"])
        if not self._check_response(res, f"{action} email", email):
            return {"ok": False, "email": email, "is_active": None, "error": self.last_error}

        self.console.log(
            f'[bold green][OK][/] "{email}" - Successfully {action}d / 操作成功'
        )
        return {"ok": True, "email": email, "is_active": active, "error": None}

    async def update_metadata(
        self, email: str, label: Optional[str], note: Optional[str]
    ) -> dict:
        self.last_error = None
        row = await self._resolve(email)
        if row is None:
            return {
                "ok": False,
                "email": email,
                "label": None,
                "note": None,
                "error": self.last_error,
            }

        new_label = label if label is not None else row.get("label") or ""
        new_note = note if note is not None else row.get("note") or ""
        res = await self.update_email_metadata(row["anonymousId"], new_label, new_note)
        if not self._check_response(res, "update email metadata", email):
            return {
                "ok": False,
                "email": email,
                "label": None,
                "note": None,
                "error": self.last_error,
            }

        self.console.log(f'[bold green][OK][/] "{email}" - Metadata updated / 已更新')
        return {
            "ok": True,
            "email": email,
            "label": new_label,
            "note": new_note,
            "error": None,
        }


