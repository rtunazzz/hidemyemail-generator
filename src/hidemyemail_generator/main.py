def _icloud_timestamp(value) -> Optional[str]:
    """Converts iCloud's millisecond createTimestamp to an ISO string."""
    if not value:
        return None
    try:
        return datetime.datetime.fromtimestamp(
            value / 1000, tz=datetime.timezone.utc
        ).isoformat()
    except (TypeError, ValueError, OSError):
        return None


def _forwarding_label(is_active: Optional[bool]) -> str:
    if is_active is None:
        return "unknown / 未知"
    return "on / 开" if is_active else "off / 关"


