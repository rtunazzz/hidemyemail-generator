enum class ICloudRegion(val id: String, val title: String, val origin: String, val defaultMaildomain: String) {
    Global("global", "Global", "https://www.icloud.com", "p68-maildomainws.icloud.com"),
    China("china", "中国区", "https://www.icloud.com.cn", "p217-maildomainws.icloud.com.cn");

    companion object {
        fun from(value: String): ICloudRegion = values().firstOrNull { it.id == value } ?: Global
    }
}

data class CookieContext(
    val cookie: String,
    val maildomainHost: String = "",
)

data class AccountInfo(
    val appleId: String,
    val fullName: String,
    val dsid: String,
    val userPartition: String,
    val maildomainHost: String,
    val hideMyEmailAvailable: Boolean,
) {
    fun summary(): String {
        val name = fullName.ifBlank { "Unknown" }
        val hme = if (hideMyEmailAvailable) "Available" else "Unknown"
        return "Apple ID: $appleId\nName: $name\nDSID: $dsid\nPartition: $userPartition\nMaildomain: $maildomainHost\nHide My Email: $hme"
    }
}

data class HmeAddress(
    val email: String,
    val label: String,
    val active: Boolean,
    val createdAt: Long,
) {
    fun createdAtText(): String {
        if (createdAt <= 0) return ""
        return SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date(createdAt))
    }
}

data class LocalAddress(
    val email: String,
    val label: String,
    val state: String,
    val updatedAt: Long,
)

