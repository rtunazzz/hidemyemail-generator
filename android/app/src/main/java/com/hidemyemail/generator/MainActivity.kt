@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun HideMyEmailApp() {
    val context = LocalContext.current
    val store = remember { HmeStore(context) }
    val repository = remember { HmeRepository() }
    val scope = rememberCoroutineScope()
    val localAddresses = remember { mutableStateListOf<LocalAddress>() }
    val remoteAddresses = remember { mutableStateListOf<HmeAddress>() }
    val generatedAddresses = remember { mutableStateListOf<HmeAddress>() }

    var selectedTab by remember { mutableStateOf(0) }
    var region by remember { mutableStateOf(store.loadRegion()) }
    var cookieInput by remember { mutableStateOf(store.loadCookie()) }
    var maildomainHost by remember { mutableStateOf(store.loadMaildomainHost()) }
    var accountSummary by remember { mutableStateOf("") }
    var label by remember { mutableStateOf("generated") }
    var countText by remember { mutableStateOf("1") }
    var showActive by remember { mutableStateOf(true) }
    var busy by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf("准备就绪") }

    fun refreshLocal() {
        localAddresses.clear()
        localAddresses.addAll(store.loadLocalAddresses())
    }

    fun currentCookieContext(): CookieContext {
        val parsed = HmeRepository.parseCookieContext(cookieInput, region)
        return if (maildomainHost.isNotBlank()) {
            parsed.copy(maildomainHost = maildomainHost.trim())
        } else {
            parsed
        }
    }

    fun saveSettings() {
        val detectedRegion = HmeRepository.detectRegion(cookieInput) ?: region
        region = detectedRegion
        store.saveSettings(detectedRegion, cookieInput, maildomainHost)
        message = "已保存本地配置"
    }

    LaunchedEffect(Unit) {
        refreshLocal()
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Text("HideMyEmail", fontWeight = FontWeight.SemiBold)
                        Text(
                            "iCloud 隐藏邮箱本地客户端",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.secondary,
                        )
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(MaterialTheme.colorScheme.background)
                .padding(padding),
        ) {
            TabRow(selectedTabIndex = selectedTab) {
                listOf("配置", "生成", "地址", "本地").forEachIndexed { index, title ->
                    Tab(selected = selectedTab == index, onClick = { selectedTab = index }, text = { Text(title) })
                }
            }

            StatusBar(message = message, busy = busy)

            when (selectedTab) {
                0 -> SettingsScreen(
                    region = region,
                    onRegionChange = {
                        region = it
                        if (maildomainHost == ICloudRegion.Global.defaultMaildomain ||
                            maildomainHost == ICloudRegion.China.defaultMaildomain
                        ) {
                            maildomainHost = ""
                        }
                    },
                    cookieInput = cookieInput,
                    onCookieChange = { cookieInput = it },
                    maildomainHost = maildomainHost,
                    onMaildomainChange = { maildomainHost = it },
                    accountSummary = accountSummary,
                    onSave = ::saveSettings,
                    onOpenICloud = {
                        context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse("${region.origin}/icloudplus/")))
                    },
                    onValidate = {
                        saveSettings()
                        val requestRegion = HmeRepository.detectRegion(cookieInput) ?: region
                        region = requestRegion
                        scope.launch {
                            busy = true
                            message = "正在校验 Cookie..."
                            val result = runCatching {
                                withContext(Dispatchers.IO) {
                                    repository.fetchAccountInfo(currentCookieContext(), requestRegion)
                                }
                            }
                            result.onSuccess { account ->
                                accountSummary = account.summary()
                                maildomainHost = account.maildomainHost
                                store.saveSettings(requestRegion, cookieInput, maildomainHost)
                                message = "Cookie 可用：${account.appleId}"
                            }.onFailure {
                                message = it.cleanMessage()
                            }
                            busy = false
                        }
                    },
                )

                1 -> GenerateScreen(
                    label = label,
                    onLabelChange = { label = it },
                    countText = countText,
                    onCountChange = { countText = it.filter(Char::isDigit).take(2) },
                    generatedAddresses = generatedAddresses,
                    onGenerate = {
                        saveSettings()
                        val requestRegion = HmeRepository.detectRegion(cookieInput) ?: region
                        region = requestRegion
                        val count = countText.toIntOrNull()?.coerceIn(1, 20) ?: 1
                        scope.launch {
                            busy = true
                            generatedAddresses.clear()
                            message = "正在生成 $count 个隐藏邮箱..."
                            val result = runCatching {
                                withContext(Dispatchers.IO) {
                                    repository.generate(currentCookieContext(), requestRegion, label.ifBlank { "generated" }, count)
                                }
                            }
                            result.onSuccess { addresses ->
                                generatedAddresses.addAll(addresses)
                                store.upsertLocalAddresses(addresses.map {
                                    LocalAddress(it.email, it.label, "unused", System.currentTimeMillis())
                                })
                                refreshLocal()
                                message = "已生成 ${addresses.size} 个地址"
                            }.onFailure {
                                message = it.cleanMessage()
                            }
                            busy = false
                        }
                    },
                )

                2 -> RemoteListScreen(
                    showActive = showActive,
                    onModeChange = { showActive = it },
                    addresses = remoteAddresses.filter { it.active == showActive },
                    onRefresh = {
                        saveSettings()
                        val requestRegion = HmeRepository.detectRegion(cookieInput) ?: region
                        region = requestRegion
                        scope.launch {
                            busy = true
                            message = "正在读取 iCloud 地址..."
                            val result = runCatching {
                                withContext(Dispatchers.IO) {
                                    repository.listAddresses(currentCookieContext(), requestRegion)
                                }
                            }
                            result.onSuccess { addresses ->
                                remoteAddresses.clear()
                                remoteAddresses.addAll(addresses)
                                store.upsertLocalAddresses(addresses.map {
                                    LocalAddress(
                                        email = it.email,
                                        label = it.label,
                                        state = if (it.active) "unused" else "trash",
                                        updatedAt = System.currentTimeMillis(),
                                    )
                                })
                                refreshLocal()
                                message = "已读取 ${addresses.size} 个 iCloud 地址"
                            }.onFailure {
                                message = it.cleanMessage()
                            }
                            busy = false
                        }
                    },
                )

                3 -> LocalScreen(
                    addresses = localAddresses,
                    onMark = { email, state ->
                        store.markAddress(email, state)
                        refreshLocal()
                        message = "已标记 $email 为 $state"
                    },
                    onClear = {
                        store.clearLocalAddresses()
                        refreshLocal()
                        message = "已清空本地地址记录"
                    },
                )
            }
        }
    }
}

@Composable
