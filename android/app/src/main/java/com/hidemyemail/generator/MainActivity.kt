class HmeStore(context: Context) {
    private val prefs = context.getSharedPreferences("hme-store", Context.MODE_PRIVATE)

    fun loadRegion(): ICloudRegion = ICloudRegion.from(prefs.getString("region", ICloudRegion.Global.id).orEmpty())

    fun loadCookie(): String = prefs.getString("cookie", "").orEmpty()

    fun loadMaildomainHost(): String = prefs.getString("maildomainHost", "").orEmpty()

    fun saveSettings(region: ICloudRegion, cookie: String, maildomainHost: String) {
        prefs.edit()
            .putString("region", region.id)
            .putString("cookie", cookie)
            .putString("maildomainHost", maildomainHost.trim())
            .apply()
    }

    fun loadLocalAddresses(): List<LocalAddress> {
        val raw = prefs.getString("localAddresses", "[]").orEmpty()
        val array = runCatching { JSONArray(raw) }.getOrElse { JSONArray() }
        return buildList {
            for (index in 0 until array.length()) {
                val item = array.optJSONObject(index) ?: continue
                add(
                    LocalAddress(
                        email = item.optString("email"),
                        label = item.optString("label"),
                        state = item.optString("state", LOCAL_STATE_UNUSED),
                        updatedAt = item.optLong("updatedAt"),
                    ),
                )
            }
        }.filter { it.email.isNotBlank() }.sortedByDescending { it.updatedAt }
    }

    fun upsertLocalAddresses(addresses: List<LocalAddress>) {
        val current = loadLocalAddresses().associateBy { it.email }.toMutableMap()
        addresses.forEach { address ->
            val existing = current[address.email]
            current[address.email] = address.copy(
                label = address.label.ifBlank { existing?.label.orEmpty() },
                state = if (existing?.state == LOCAL_STATE_USED) existing.state else address.state,
                updatedAt = System.currentTimeMillis(),
            )
        }
        saveLocalAddresses(current.values.sortedByDescending { it.updatedAt })
    }

    fun markAddress(email: String, state: String) {
        val current = loadLocalAddresses().map {
            if (it.email == email) it.copy(state = state, updatedAt = System.currentTimeMillis()) else it
        }
        saveLocalAddresses(current)
    }

    fun clearLocalAddresses() {
        prefs.edit().putString("localAddresses", "[]").apply()
    }

    private fun saveLocalAddresses(addresses: Collection<LocalAddress>) {
        val array = JSONArray()
        addresses.forEach { address ->
            array.put(
                JSONObject()
                    .put("email", address.email)
                    .put("label", address.label)
                    .put("state", address.state)
                    .put("updatedAt", address.updatedAt),
            )
        }
        prefs.edit().putString("localAddresses", array.toString()).apply()
    }
}

internal class HmeRepository(
    private val transport: HmeTransport = OkHttpHmeTransport(),
) {
    fun fetchAccountInfo(context: CookieContext, region: ICloudRegion): AccountInfo {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        val url = when (region) {
            ICloudRegion.Global -> "https://setup.icloud.com/setup/ws/1/validate"
            ICloudRegion.China -> "https://setup.icloud.com.cn/setup/ws/1/validate"
        }
        val response = transport.execute(baseRequest(url, context.cookie, region).get().build())
        val data = parseResponse(response, "validate account")
        val dsInfo = data.optJSONObject("dsInfo") ?: JSONObject()
        val webservices = data.optJSONObject("webservices") ?: JSONObject()
        val maildomain = webservices.optJSONObject("maildomainws")
        val partition = data.optString("userPartition")
        val normalizedContextHost = normalizeMaildomainHost(context.maildomainHost, region)
        val detectedHost = normalizedContextHost.ifBlank {
            when {
                maildomain?.optString("url").orEmpty().isNotBlank() -> normalizeMaildomainHost(
                    Uri.parse(maildomain?.optString("url")).host.orEmpty(),
                    region,
                )
                partition.isNotBlank() -> "p$partition-maildomainws.icloud.${if (region == ICloudRegion.China) "com.cn" else "com"}"
                else -> region.defaultMaildomain
            }
        }
        val name = listOf(dsInfo.optString("firstName"), dsInfo.optString("lastName"))
            .filter { it.isNotBlank() }
            .joinToString(" ")
            .ifBlank { dsInfo.optString("fullName") }

        return AccountInfo(
            appleId = dsInfo.optString("appleId"),
            fullName = name,
            dsid = dsInfo.optString("dsid"),
            userPartition = partition,
            maildomainHost = detectedHost.ifBlank { region.defaultMaildomain },
            hideMyEmailAvailable = dsInfo.optBoolean("isHideMyEmailFeatureAvailable"),
        )
    }

    fun generate(
        context: CookieContext,
        region: ICloudRegion,
        label: String,
        count: Int,
        onReserved: (HmeAddress) -> Unit = {},
    ): GenerationResult {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        require(count > 0) { "Count must be positive" }
        val host = resolveMaildomainHost(context, region)
        val out = mutableListOf<HmeAddress>()
        repeat(count) {
            try {
                val generated = requestJson(
                    method = "POST",
                    url = "https://$host${HmeEndpoints.generate}",
                    region = region,
                    cookie = context.cookie,
                    payload = JSONObject().put("langCode", region.generateLangCode),
                )
                val generatedData = ensureSuccess(generated, "generate email")
                val email = generatedData.getJSONObject("result").getString("hme")
                val reserved = requestJson(
                    method = "POST",
                    url = "https://$host${HmeEndpoints.reserve}",
                    region = region,
                    cookie = context.cookie,
                    payload = JSONObject()
                        .put("hme", email)
                        .put("label", label)
                        .put("note", DEFAULT_NOTE),
                )
                val reservedData = ensureSuccess(reserved, "reserve email")
                val address = HmeAddress(
                    anonymousId = reservedData.optJSONObject("result")?.optString("anonymousId").orEmpty(),
                    email = email,
                    label = label,
                    note = DEFAULT_NOTE,
                    active = true,
                    createdAt = System.currentTimeMillis(),
                )
                out += address
                onReserved(address)
            } catch (failure: Exception) {
                if (failure is CancellationException) throw failure
                return GenerationResult(out, failure)
            }
        }
        return GenerationResult(out)
    }

    fun listAddresses(context: CookieContext, region: ICloudRegion): List<HmeAddress> {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        val data = requestJson(
            method = "GET",
            url = "https://${resolveMaildomainHost(context, region)}${HmeEndpoints.list}",
            region = region,
            cookie = context.cookie,
        )
        return parseHmeAddresses(ensureSuccess(data, "list emails"))
    }

    fun updateAddressMetadata(
        context: CookieContext,
        region: ICloudRegion,
        anonymousId: String,
        label: String,
        note: String,
    ) {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        require(anonymousId.isNotBlank()) { "Missing iCloud address identifier" }
        val data = requestJson(
            method = "POST",
            url = "https://${resolveMaildomainHost(context, region)}${HmeEndpoints.updateMetadata}",
            region = region,
            cookie = context.cookie,
            payload = updateMetadataPayload(anonymousId, label, note),
        )
        ensureSuccess(data, "update email metadata")
    }

    fun deactivateAddress(context: CookieContext, region: ICloudRegion, anonymousId: String) {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        require(anonymousId.isNotBlank()) { "Missing iCloud address identifier" }
        val data = requestJson(
            method = "POST",
            url = "https://${resolveMaildomainHost(context, region)}${HmeEndpoints.deactivate}",
            region = region,
            cookie = context.cookie,
            payload = anonymousIdPayload(anonymousId),
        )
        ensureSuccess(data, "deactivate email")
    }

    fun reactivateAddress(context: CookieContext, region: ICloudRegion, anonymousId: String) {
        require(context.cookie.isNotBlank()) { "Cookie is empty" }
        require(anonymousId.isNotBlank()) { "Missing iCloud address identifier" }
        val data = requestJson(
            method = "POST",
            url = "https://${resolveMaildomainHost(context, region)}${HmeEndpoints.reactivate}",
            region = region,
            cookie = context.cookie,
            payload = anonymousIdPayload(anonymousId),
        )
        ensureSuccess(data, "reactivate email")
    }

    private fun requestJson(
        method: String,
        url: String,
        region: ICloudRegion,
        cookie: String,
        payload: JSONObject? = null,
    ): HmeJsonResponse {
        val httpUrl = url.toHttpUrl().newBuilder()
            .addQueryParameter("clientBuildNumber", HmeRequestDefaults.clientBuildNumber)
            .addQueryParameter("clientMasteringNumber", HmeRequestDefaults.clientMasteringNumber)
            .addQueryParameter("clientId", "")
            .addQueryParameter("dsid", "")
            .build()
        val builder = baseRequest(httpUrl.toString(), cookie, region)
        if (method == "POST") {
            // text/plain matches the iCloud web client; OkHttp derives Content-Type from the body,
            // so setting it here rather than as a header is what actually reaches Apple.
            val body = (payload ?: JSONObject()).toString().toRequestBody("text/plain".toMediaType())
            builder.post(body)
        } else {
            builder.get()
        }
        val response = transport.execute(builder.build())
        return HmeJsonResponse(parseResponse(response, "perform request"), response.retryAfterSeconds)
    }

    private fun baseRequest(url: String, cookie: String, region: ICloudRegion): Request.Builder {
        return Request.Builder()
            .url(url)
            .header("Connection", "keep-alive")
            .header("Pragma", "no-cache")
            .header("Cache-Control", "no-cache")
            .header("User-Agent", HmeRequestDefaults.userAgent)
            .header("Content-Type", "text/plain")
            .header("Accept", "*/*")
            .header("Sec-GPC", "1")
            .header("Origin", region.origin)
            .header("Sec-Fetch-Site", "same-site")
            .header("Sec-Fetch-Mode", "cors")
            .header("Sec-Fetch-Dest", "empty")
            .header("Referer", "${region.origin}/")
            .header("Accept-Language", acceptLanguage(region))
            .header("sec-ch-ua", HmeRequestDefaults.secChUa)
            .header("sec-ch-ua-mobile", "?1")
            .header("sec-ch-ua-platform", "\"Android\"")
            .header("Cookie", cookie.trim())
    }

    private fun resolveMaildomainHost(context: CookieContext, region: ICloudRegion): String {
        return normalizeMaildomainHost(context.maildomainHost, region).ifBlank { region.defaultMaildomain }
    }

    private fun parseResponse(response: HmeHttpResponse, action: String): JSONObject {
        if (response.body.isBlank()) {
            throw HmeRequestException("iCloud returned an empty response (HTTP ${response.code})", response.retryAfterSeconds)
        }
        val data = try {
            JSONObject(response.body)
        } catch (_: Exception) {
            throw HmeRequestException("iCloud returned invalid JSON while attempting to $action", response.retryAfterSeconds)
        }
        if (!response.isSuccessful) {
            throw HmeRequestException(
                failureReason(data).ifBlank { "iCloud request failed (HTTP ${response.code})" },
                response.retryAfterSeconds,
            )
        }
        return data
    }

    private fun ensureSuccess(response: HmeJsonResponse, action: String): JSONObject {
        if (response.data.optBoolean("success", false)) return response.data
        throw HmeRequestException(
            "Failed to $action: ${failureReason(response.data)}",
            response.retryAfterSeconds,
        )
    }

    private fun failureReason(data: JSONObject): String {
        return when (val errorValue = data.opt("error")) {
            is JSONObject -> errorValue.optString("errorMessage", errorValue.toString())
            null -> data.optString("reason", data.toString())
            else -> data.optString("reason", errorValue.toString())
        }
    }

    private data class HmeJsonResponse(
        val data: JSONObject,
        val retryAfterSeconds: Int?,
    )

    companion object {
        fun parseHmeAddresses(data: JSONObject): List<HmeAddress> {
            val emails = data.optJSONObject("result")?.optJSONArray("hmeEmails") ?: JSONArray()
            return buildList {
                for (index in 0 until emails.length()) {
                    val item = emails.optJSONObject(index) ?: continue
                    add(
                        HmeAddress(
                            anonymousId = item.optString("anonymousId"),
                            email = item.optString("hme"),
                            label = item.optString("label"),
                            note = item.optString("note"),
                            active = item.optBoolean("isActive"),
                            createdAt = item.optLong("createTimestamp"),
                        ),
                    )
                }
            }.filter { it.email.isNotBlank() }.sortedByDescending { it.createdAt }
        }

        fun updateMetadataPayload(anonymousId: String, label: String, note: String): JSONObject {
            return JSONObject()
                .put("anonymousId", anonymousId)
                .put("label", label)
                .put("note", note)
        }

        fun anonymousIdPayload(anonymousId: String): JSONObject = JSONObject().put("anonymousId", anonymousId)

        fun acceptLanguage(region: ICloudRegion): String {
            return when (region) {
                ICloudRegion.Global -> "en-US,en;q=0.7"
                ICloudRegion.China -> "zh-CN,zh;q=0.9,en-US;q=0.8,en;q=0.7"
            }
        }

        fun parseCookieContext(raw: String, region: ICloudRegion): CookieContext {
            val rawContent = raw.lineSequence()
                .map { it.trim() }
                .filter { it.isNotBlank() && !it.startsWith("//") }
                .joinToString("\n")
                .trim()
            val content = rawContent
                .replace("^\\\"", "\"")
                .replace("^'", "'")
            if (rawContent.isBlank()) return CookieContext("")

            val resolvedRegion = detectRegion(content) ?: region
            val explicitHost = Regex("""(?m)^HIDEMYEMAIL_MAILDOMAIN_HOST=([A-Za-z0-9.-]+)\s*$""")
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
                .orEmpty()
                .trim()
                .let { normalizeMaildomainHost(it, resolvedRegion) }
            val base64Cookie = Regex("""(?m)^HIDEMYEMAIL_COOKIE_BASE64=([A-Za-z0-9+/=]+)\s*$""")
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
            if (!base64Cookie.isNullOrBlank()) {
                val decoded = runCatching {
                    String(Base64.decode(base64Cookie, Base64.DEFAULT), Charsets.UTF_8).trim()
                }.getOrDefault("")
                return CookieContext(decoded, explicitHost)
            }

            val shardHost = Regex("""https://(p\d+)-[^/\s'"]+\.icloud\.com(?:\.cn)?""")
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
                ?.let { "$it-maildomainws.icloud.${if (resolvedRegion == ICloudRegion.China) "com.cn" else "com"}" }
                .orEmpty()
            val maildomainHost = explicitHost.ifBlank { shardHost }

            val cmdCookieArg = Regex(
                """(?:^|\s)(?:-b|--cookie)\s+\^\"(.+?)\^\"\s+\^?\s*-[A-Za-z]""",
                setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL),
            ).find(rawContent)?.groupValues?.getOrNull(1)
            if (!cmdCookieArg.isNullOrBlank()) {
                val cookie = cmdCookieArg
                    .replace("^\\^\"", "\"")
                    .replace("\\\"", "\"")
                    .replace("^\"", "\"")
                    .replace("\r", "")
                    .replace("\n", "")
                    .trim()
                return CookieContext(cookie, maildomainHost)
            }

            val cookieFromDoubleQuote = Regex("""(?:^|\s)(?:-b|--cookie)\s+"([^"]+)"""", RegexOption.IGNORE_CASE)
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
            if (!cookieFromDoubleQuote.isNullOrBlank()) {
                return CookieContext(cookieFromDoubleQuote.trim(), maildomainHost)
            }

            val cookieFromSingleQuote = Regex("""(?:^|\s)(?:-b|--cookie)\s+'([^']+)'""", RegexOption.IGNORE_CASE)
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
            if (!cookieFromSingleQuote.isNullOrBlank()) {
                return CookieContext(cookieFromSingleQuote.trim(), maildomainHost)
            }

            val cookieHeader = Regex("""cookie\s*:\s*([^'"\r\n]+)""", RegexOption.IGNORE_CASE)
                .find(content)
                ?.groupValues
                ?.getOrNull(1)
            if (!cookieHeader.isNullOrBlank()) {
                return CookieContext(cookieHeader.trim(), maildomainHost)
            }

            val rawCookie = content.lines().firstOrNull().orEmpty().trim()
            if (Regex("""^[^=;\s]+=""").containsMatchIn(rawCookie)) {
                return CookieContext(rawCookie, maildomainHost)
            }
            return CookieContext("", maildomainHost)
        }

        fun normalizeMaildomainHost(host: String, region: ICloudRegion): String {
            val cleanHost = host
                .trim()
                .removePrefix("https://")
                .removePrefix("http://")
                .substringBefore('/')
            val shard = Regex("""^(p\d+)-maildomainws\.icloud\.com(?:\.cn)?$""")
                .matchEntire(cleanHost)
                ?.groupValues
                ?.getOrNull(1)
            return if (shard == null) {
                cleanHost
            } else {
                "$shard-maildomainws.icloud.${if (region == ICloudRegion.China) "com.cn" else "com"}"
            }
        }

        fun detectRegion(raw: String): ICloudRegion? {
            if (raw.contains("icloud.com.cn", ignoreCase = true)) return ICloudRegion.China
            val declaredRegion = Regex("""(?m)^HIDEMYEMAIL_REGION=(global|china)\s*$""", RegexOption.IGNORE_CASE)
                .find(raw)
                ?.groupValues
                ?.getOrNull(1)
                ?.lowercase(Locale.ROOT)
            return declaredRegion?.let(ICloudRegion::from)
        }
    }
}

private fun Throwable.cleanMessage(): String = message?.takeIf { it.isNotBlank() } ?: javaClass.simpleName

private fun Context.copyToClipboard(text: String) {
    val clipboard = getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    clipboard.setPrimaryClip(ClipData.newPlainText("HideMyEmail", text))
}
