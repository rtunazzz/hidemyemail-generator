data class AccountInfo(
    val appleId: String,
    val fullName: String,
    val dsid: String,
    val userPartition: String,
    val maildomainHost: String,
    val hideMyEmailAvailable: Boolean,
) {
    fun summary(context: Context): String {
        val unknown = context.getString(R.string.value_unknown)
        return listOf(
            context.getString(R.string.account_apple_id, appleId.ifBlank { unknown }),
            context.getString(R.string.account_name, fullName.ifBlank { unknown }),
            context.getString(R.string.account_dsid, dsid.ifBlank { unknown }),
            context.getString(R.string.account_partition, userPartition.ifBlank { unknown }),
            context.getString(R.string.account_maildomain, maildomainHost.ifBlank { unknown }),
            context.getString(
                R.string.account_hme,
                context.getString(if (hideMyEmailAvailable) R.string.value_available else R.string.value_unknown),
            ),
        ).joinToString("\n")
    }
}

data class HmeAddress(
    val anonymousId: String,
    val email: String,
    val label: String,
    val note: String,
    val active: Boolean,
    val createdAt: Long,
) {
    fun createdAtText(): String {
        if (createdAt <= 0) return ""
        return SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date(createdAt))
    }
}

data class LocalAddress(
    val email: String,
    val label: String,
    val state: String,
    val updatedAt: Long,
)

data class GenerationResult(
    val addresses: List<HmeAddress>,
    val failure: Throwable? = null,
) {
    val retryAfterSeconds: Int?
        get() = (failure as? HmeRequestException)?.retryAfterSeconds
}

internal data class HmeHttpResponse(
    val code: Int,
    val body: String,
    val retryAfterSeconds: Int? = null,
) {
    val isSuccessful: Boolean
        get() = code in 200..299
}

internal fun interface HmeTransport {
    fun execute(request: Request): HmeHttpResponse
}

internal class HmeRequestException(
    message: String,
    val retryAfterSeconds: Int? = null,
) : IllegalStateException(message)

private class OkHttpHmeTransport : HmeTransport {
    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    override fun execute(request: Request): HmeHttpResponse {
        return client.newCall(request).execute().use { response ->
            HmeHttpResponse(
                code = response.code,
                body = response.body?.string().orEmpty(),
                retryAfterSeconds = response.header("Retry-After")?.toIntOrNull(),
            )
        }
    }
}

