@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun HideMyEmailApp() {
    val context = LocalContext.current
    val store = remember { HmeStore(context) }
    val repository = remember { HmeRepository() }
    val scope = rememberCoroutineScope()
    val localAddresses = remember { mutableStateListOf<LocalAddress>() }
    val remoteAddresses = remember { mutableStateListOf<HmeAddress>() }
    val generatedAddresses = remember { mutableStateListOf<HmeAddress>() }

    var selectedTab by remember { mutableStateOf(0) }
    var region by remember { mutableStateOf(store.loadRegion()) }
    var cookieInput by remember { mutableStateOf(store.loadCookie()) }
    var maildomainHost by remember { mutableStateOf(store.loadMaildomainHost()) }
    var accountSummary by remember { mutableStateOf("") }
    var label by remember { mutableStateOf("generated") }
    var countText by remember { mutableStateOf("1") }
    var showActive by remember { mutableStateOf(true) }
    var managedAddress by remember { mutableStateOf<HmeAddress?>(null) }
    var busy by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf(context.getString(R.string.status_ready)) }

    fun refreshLocal() {
        localAddresses.clear()
        localAddresses.addAll(store.loadLocalAddresses())
    }

    fun toLocalAddress(address: HmeAddress): LocalAddress {
        return LocalAddress(
            email = address.email,
            label = address.label,
            state = if (address.active) LOCAL_STATE_UNUSED else LOCAL_STATE_TRASH,
            updatedAt = System.currentTimeMillis(),
        )
    }

    fun applyRemoteAddresses(addresses: List<HmeAddress>) {
        remoteAddresses.clear()
        remoteAddresses.addAll(addresses)
        store.upsertLocalAddresses(addresses.map(::toLocalAddress))
        refreshLocal()
    }

    fun requestRegion(): ICloudRegion = HmeRepository.detectRegion(cookieInput) ?: region

    fun currentCookieContext(): CookieContext {
        val resolvedRegion = requestRegion()
        val parsed = HmeRepository.parseCookieContext(cookieInput, resolvedRegion)
        return if (maildomainHost.isNotBlank()) {
            parsed.copy(maildomainHost = HmeRepository.normalizeMaildomainHost(maildomainHost, resolvedRegion))
        } else {
            parsed
        }
    }

    fun saveSettings() {
        val detectedRegion = requestRegion()
        val parsed = HmeRepository.parseCookieContext(cookieInput, detectedRegion)
        val resolvedHost = if (maildomainHost.isNotBlank()) {
            HmeRepository.normalizeMaildomainHost(maildomainHost, detectedRegion)
        } else {
            parsed.maildomainHost
        }
        region = detectedRegion
        maildomainHost = resolvedHost
        store.saveSettings(detectedRegion, cookieInput, resolvedHost)
        message = context.getString(R.string.status_settings_saved)
    }

    suspend fun syncRemoteAddresses(resolvedRegion: ICloudRegion): Int {
        val addresses = withContext(Dispatchers.IO) {
            repository.listAddresses(currentCookieContext(), resolvedRegion)
        }
        applyRemoteAddresses(addresses)
        return addresses.size
    }

    fun performAddressAction(
        address: HmeAddress,
        progressRes: Int,
        successRes: Int,
        action: (CookieContext, ICloudRegion, HmeAddress) -> Unit,
    ) {
        saveSettings()
        val resolvedRegion = requestRegion()
        region = resolvedRegion
        scope.launch {
            busy = true
            message = context.getString(progressRes)
            val result = runCatching {
                withContext(Dispatchers.IO) {
                    action(currentCookieContext(), resolvedRegion, address)
                }
                syncRemoteAddresses(resolvedRegion)
            }
            result.onSuccess {
                managedAddress = null
                message = context.getString(successRes)
            }.onFailure {
                message = context.getString(R.string.operation_failed, it.cleanMessage())
            }
            busy = false
        }
    }

    LaunchedEffect(Unit) {
        refreshLocal()
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Text("HideMyEmail", fontWeight = FontWeight.SemiBold)
                        Text(
                            stringResource(R.string.app_subtitle),
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.secondary,
                        )
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(MaterialTheme.colorScheme.background)
                .padding(padding),
        ) {
            val tabs = listOf(
                stringResource(R.string.tab_settings),
                stringResource(R.string.tab_generate),
                stringResource(R.string.tab_addresses),
                stringResource(R.string.tab_local),
            )
            TabRow(selectedTabIndex = selectedTab) {
                tabs.forEachIndexed { index, title ->
                    Tab(
                        selected = selectedTab == index,
                        onClick = { selectedTab = index },
                        text = { Text(title) },
                    )
                }
            }

            StatusBar(message = message, busy = busy)

            when (selectedTab) {
                0 -> SettingsScreen(
                    region = region,
                    onRegionChange = {
                        region = it
                        if (
                            maildomainHost == ICloudRegion.Global.defaultMaildomain ||
                            maildomainHost == ICloudRegion.China.defaultMaildomain
                        ) {
                            maildomainHost = ""
                        }
                    },
                    cookieInput = cookieInput,
                    onCookieChange = { cookieInput = it },
                    maildomainHost = maildomainHost,
                    onMaildomainChange = { maildomainHost = it },
                    accountSummary = accountSummary,
                    onSave = ::saveSettings,
                    onOpenICloud = {
                        context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse("${region.origin}/icloudplus/")))
                    },
                    onValidate = {
                        saveSettings()
                        val resolvedRegion = requestRegion()
                        region = resolvedRegion
                        scope.launch {
                            busy = true
                            message = context.getString(R.string.status_validating_cookie)
                            val result = runCatching {
                                withContext(Dispatchers.IO) {
                                    repository.fetchAccountInfo(currentCookieContext(), resolvedRegion)
                                }
                            }
                            result.onSuccess { account ->
                                accountSummary = account.summary(context)
                                maildomainHost = account.maildomainHost
                                store.saveSettings(resolvedRegion, cookieInput, maildomainHost)
                                message = context.getString(R.string.status_cookie_valid, account.appleId)
                            }.onFailure {
                                message = context.getString(R.string.operation_failed, it.cleanMessage())
                            }
                            busy = false
                        }
                    },
                )

                1 -> GenerateScreen(
                    label = label,
                    onLabelChange = { label = it },
                    countText = countText,
                    onCountChange = { countText = it.filter(Char::isDigit).take(2) },
                    generatedAddresses = generatedAddresses,
                    onGenerate = {
                        saveSettings()
                        val resolvedRegion = requestRegion()
                        region = resolvedRegion
                        val count = countText.toIntOrNull()?.coerceIn(1, 20) ?: 1
                        scope.launch {
                            busy = true
                            generatedAddresses.clear()
                            message = context.getString(R.string.status_generating, count)
                            val result = runCatching {
                                withContext(Dispatchers.IO) {
                                    repository.generate(
                                        context = currentCookieContext(),
                                        region = resolvedRegion,
                                        label = label.ifBlank { "generated" },
                                        count = count,
                                        onReserved = { address ->
                                            store.upsertLocalAddresses(listOf(toLocalAddress(address)))
                                        },
                                    )
                                }
                            }
                            result.onSuccess { generation ->
                                generatedAddresses.addAll(generation.addresses)
                                store.upsertLocalAddresses(generation.addresses.map(::toLocalAddress))
                                refreshLocal()
                                message = generationStatus(context, generation, count)
                            }.onFailure {
                                message = context.getString(R.string.operation_failed, it.cleanMessage())
                            }
                            busy = false
                        }
                    },
                )

                2 -> RemoteListScreen(
                    showActive = showActive,
                    onModeChange = { showActive = it },
                    addresses = remoteAddresses.filter { it.active == showActive },
                    onManage = { managedAddress = it },
                    onRefresh = {
                        saveSettings()
                        val resolvedRegion = requestRegion()
                        region = resolvedRegion
                        scope.launch {
                            busy = true
                            message = context.getString(R.string.status_loading_addresses)
                            val result = runCatching {
                                syncRemoteAddresses(resolvedRegion)
                            }
                            result.onSuccess { count ->
                                message = context.resources.getQuantityString(
                                    R.plurals.addresses_loaded,
                                    count,
                                    count,
                                )
                            }.onFailure {
                                message = context.getString(R.string.operation_failed, it.cleanMessage())
                            }
                            busy = false
                        }
                    },
                )

                3 -> LocalScreen(
                    addresses = localAddresses,
                    onMark = { email, state ->
                        store.markAddress(email, state)
                        refreshLocal()
                        message = context.getString(
                            R.string.status_address_marked,
                            email,
                            localStateTitle(context, state),
                        )
                    },
                    onClear = {
                        store.clearLocalAddresses()
                        refreshLocal()
                        message = context.getString(R.string.status_local_cleared)
                    },
                )
            }
        }
    }

    managedAddress?.let { address ->
        HmeAddressManagementDialog(
            address = address,
            onDismiss = { managedAddress = null },
            onSave = { newLabel, newNote ->
                performAddressAction(
                    address = address,
                    progressRes = R.string.status_updating_address,
                    successRes = R.string.status_address_updated,
                ) { cookieContext, resolvedRegion, item ->
                    repository.updateAddressMetadata(
                        context = cookieContext,
                        region = resolvedRegion,
                        anonymousId = item.anonymousId,
                        label = newLabel,
                        note = newNote,
                    )
                }
            },
            onChangeActivity = {
                if (address.active) {
                    performAddressAction(
                        address = address,
                        progressRes = R.string.status_deactivating_address,
                        successRes = R.string.status_address_deactivated,
                    ) { cookieContext, resolvedRegion, item ->
                        repository.deactivateAddress(cookieContext, resolvedRegion, item.anonymousId)
                    }
                } else {
                    performAddressAction(
                        address = address,
                        progressRes = R.string.status_reactivating_address,
                        successRes = R.string.status_address_reactivated,
                    ) { cookieContext, resolvedRegion, item ->
                        repository.reactivateAddress(cookieContext, resolvedRegion, item.anonymousId)
                    }
                }
            },
        )
    }
}

private fun generationStatus(context: Context, result: GenerationResult, requestedCount: Int): String {
    if (result.failure == null) {
        return context.resources.getQuantityString(
            R.plurals.addresses_generated,
            result.addresses.size,
            result.addresses.size,
        )
    }
    if (result.addresses.isEmpty()) {
        return context.getString(R.string.operation_failed, result.failure.cleanMessage())
    }
    val retryAfter = result.retryAfterSeconds
    return if (retryAfter == null) {
        context.getString(
            R.string.status_generation_partial,
            result.addresses.size,
            requestedCount,
            result.failure.cleanMessage(),
        )
    } else {
        context.getString(
            R.string.status_generation_partial_retry,
            result.addresses.size,
            requestedCount,
            retryAfter,
        )
    }
}

@Composable
private fun StatusBar(message: String, busy: Boolean) {
    Surface(
        tonalElevation = 1.dp,
        color = MaterialTheme.colorScheme.surface,
        modifier = Modifier.fillMaxWidth(),
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 16.dp, vertical = 10.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            if (busy) {
                CircularProgressIndicator(modifier = Modifier.width(18.dp).height(18.dp), strokeWidth = 2.dp)
            } else {
                Icon(Icons.Default.Verified, contentDescription = null, tint = MaterialTheme.colorScheme.primary)
            }
            Text(message, style = MaterialTheme.typography.bodyMedium, maxLines = 2, overflow = TextOverflow.Ellipsis)
        }
    }
}

